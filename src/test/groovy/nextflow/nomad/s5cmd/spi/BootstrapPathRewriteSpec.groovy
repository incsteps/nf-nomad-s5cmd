package nextflow.nomad.s5cmd.spi

import nextflow.processor.TaskRun
import spock.lang.IgnoreIf
import spock.lang.Specification
import spock.lang.TempDir
import spock.lang.Unroll

import java.nio.file.Files
import java.nio.file.Path

/**
 * Step 3 of the worker bootstrap rewrites absolute work-dir paths in
 * .command.run to relative ones, because the S3 work dir does not exist inside
 * the task container. It used the POSIX class [[:space:]], which mawk 1.3.3
 * (Debian's default awk, and the awk in many biocontainers images) does not
 * support: the gsub silently matched nothing, the file kept its absolute
 * paths, and any task whose launcher re-invokes .command.run — a non-bash
 * shebang template — died with "No such file or directory".
 *
 * The fixture is a .command.run generated by Nextflow 26.04.3 for a
 * python-shebang template with tracing on, with its work dir replaced by an
 * S3-style path. It carries all five reference shapes the rewrite handles.
 */
class BootstrapPathRewriteSpec extends Specification {

    static final String REMOTE_WD = 's3://su-sdsct-ceri/users/ottovan/workdir/dev3/87/3c06cc5e8a1d2b7f90e4c6a3d8b1f207/'
    static final String ABS_WD    = '/su-sdsct-ceri/users/ottovan/workdir/dev3/87/3c06cc5e8a1d2b7f90e4c6a3d8b1f207'

    @TempDir
    Path tempDir

    static boolean dockerAvailable() {
        try {
            def p = ['docker', 'info'].execute()
            p.waitFor()
            return p.exitValue() == 0
        } catch (Throwable ignored) {
            return false
        }
    }

    private String renderedScript() {
        Path sessionDir = tempDir.resolve('sess')
        Path workDir = sessionDir.resolve('ab').resolve('cdef1234')
        Files.createDirectories(workDir)
        def task = Mock(TaskRun) { getWorkDir() >> workDir }
        def session = [s5cmd: [
            enabled: true, binary: '/nxf-work/bin/s5cmd',
            s3     : [endpoint: 'http://rustfs:9900', usePathStyle: true, accessKeyId: 'AK', secretAccessKey: 'SK'],
            workDir: [enabled: true, bucket: 's3://nextflow-work', prefix: 'sessions/abc'],
        ]]
        // Nomad turns $${ into ${ before the args reach the driver.
        return new S5cmdNomadInterop(task, session, sessionDir).bootstrapScript().replace('$${', '${')
    }

    /** The step-3 block exactly as rendered: from its log line to its closing column-0 fi. */
    private String step3Block() {
        String s = renderedScript()
        int start = s.indexOf('log "step 3: patch absolute paths in .command.run"')
        assert start >= 0
        int end = s.indexOf('\nfi\n', start)
        assert end > start
        return s.substring(start, end + 4)
    }

    private static String fixture() {
        BootstrapPathRewriteSpec.getResourceAsStream('/fixtures/command-run-python-template.txt').text
    }

    def 'the bootstrap uses no POSIX bracket classes'() {
        // mawk 1.3.3 parses [[:space:]] as an ordinary bracket expression and
        // matches nothing. The bootstrap runs under whatever awk the user's
        // container ships, so it must stay within the common dialect.
        // Match any class, not just the literal "[[:": the shipped form was
        // [^[:space:]], where the negation sits between the two brackets.
        expect:
        !(renderedScript() =~ /\[:[a-z]+:\]/)
    }

    def 'the fixture really does carry absolute work-dir references'() {
        expect: 'otherwise every rewrite test below is vacuous'
        fixture().count(ABS_WD + '/') == 5
    }

    @Unroll
    @IgnoreIf({ !dockerAvailable() })
    def 'step 3 rewrites every absolute path under #awkName'() {
        given:
        Path dir = Files.createDirectories(tempDir.resolve("run-${awkName.replaceAll(/\W/, '_')}"))
        Files.writeString(dir.resolve('fixture.txt'), fixture())
        Files.writeString(dir.resolve('harness.sh'), harness(step3Block()))

        when:
        def r = runInDocker(image, dir)

        then: 'the block completes'
        r.out.contains('HARNESS_EXIT=0')

        and: 'no absolute work-dir path survives'
        def patched = r.out.substring(r.out.indexOf('---PATCHED---'))
        !patched.contains(ABS_WD)

        and: 'each shape was rewritten to its relative form'
        patched.contains('/bin/bash .command.run nxf_trace')
        patched.contains('/usr/bin/env python3 .command.sh')
        patched.contains('> .exitcode')
        patched.contains('touch .command.begin')

        where:
        awkName            | image
        'mawk 1.3.3'       | 'quay.io/biocontainers/multiqc:1.14--pyhdfd78af_0'
        'busybox awk'      | 'quay.io/biocontainers/python:3.8.3'
        'mawk 1.3.4'       | 'ubuntu:24.04'
    }

    @IgnoreIf({ !dockerAvailable() })
    def 'step 3 fails loudly when the rewrite does not take effect'() {
        // Simulate an awk that cannot run the regex: shim it to a no-op. The
        // guard must catch the surviving absolute path with a fixed-string
        // search, not trust the same tool that just failed.
        given:
        Path dir = Files.createDirectories(tempDir.resolve('run-noop-awk'))
        Files.writeString(dir.resolve('fixture.txt'), fixture())
        Files.writeString(dir.resolve('harness.sh'), harness(step3Block(), true))

        when:
        def r = runInDocker('ubuntu:24.04', dir)

        then:
        r.out.contains('HARNESS_EXIT=1')
        r.err.contains('FATAL: .command.run still references')
    }

    private static String harness(String block, boolean noopAwk = false) {
        """\
        set -u
        cd /tmp
        NF_DBG=/tmp/dbg.log
        log() { echo "\$*" >> "\$NF_DBG"; }
        NXF_S5CMD_REMOTE_WORKDIR='${REMOTE_WD}'
        cp /w/fixture.txt .command.run
        ${noopAwk ? 'awk() { cat "$2"; }' : ''}
        ( ${block}
        ) ; echo "HARNESS_EXIT=\$?"
        echo '---PATCHED---'
        cat .command.run
        """.stripIndent()
    }

    private static Map runInDocker(String image, Path dir) {
        def proc = ['docker', 'run', '--rm', '-v', "${dir}:/w:ro", image, 'sh', '/w/harness.sh'].execute()
        def out = new StringBuilder(), err = new StringBuilder()
        proc.waitForProcessOutput(out, err)
        return [out: out.toString(), err: err.toString()]
    }
}
